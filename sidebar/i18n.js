  let language = "de";

  function t(key, values) {
    let text = (STRINGS[language] && STRINGS[language][key]) || STRINGS.de[key] || key;
    if (values) for (const [name, value] of Object.entries(values)) text = text.split(`{${name}}`).join(String(value));
    return text;
  }

  const tabCount = (count) => (count === 1 ? t("tool.tab") : t("tool.tabs", { count }));

  function detect() {
    const browserLanguage = (typeof navigator !== "undefined" && navigator.language) || "de";
    return browserLanguage.toLowerCase().startsWith("de") ? "de" : "en";
  }

  /* "auto" folgt der Browsersprache. */
  function setLanguage(wanted) {
    language = STRINGS[wanted] ? wanted : detect();
    if (typeof document !== "undefined") document.documentElement.lang = language;
    return language;
  }

  /* Setzt alle Texte im HTML: data-i18n (Text), data-i18n-title (Tooltip + aria-label), data-i18n-placeholder. */
  function apply(scope) {
    scope.querySelectorAll("[data-i18n]").forEach((node) => (node.textContent = t(node.dataset.i18n)));
    scope.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.title = t(node.dataset.i18nTitle);
      node.setAttribute("aria-label", node.title);
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((node) => (node.placeholder = t(node.dataset.i18nPlaceholder)));
  }

  root.I18n = { t, tabCount, setLanguage, detect, apply, strings: STRINGS, get language() { return language; } };
  if (typeof module !== "undefined" && module.exports) module.exports = root.I18n;
